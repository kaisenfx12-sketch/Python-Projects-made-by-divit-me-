# Q1. Print only the even numbers from a list of 10 numbers
numbers = [12, 7, 18, 5, 22, 9, 30, 14, 3, 16]
print("Q1: Even numbers are:")
for n in numbers:
    if n % 2 == 0:
        print(n)

# Q2. Calculate total marks from a list of 5 student marks
marks = [78, 85, 90, 88, 94]
total_marks = 0
print("\nQ2: Total marks:")
for mark in marks:
    total_marks += mark
print("Total marks =", total_marks)

# Q3. Print fruits with message "I like ___"
fruits = ["Apple", "Banana", "Mango", "Orange", "Grapes"]
print("\nQ3: Fruit likes:")
for fruit in fruits:
    print(f"I like {fruit}")

# Q4. Largest number in a tuple
numbers_tuple = (12, 45, 7, 89, 33)
largest = numbers_tuple[0]
print("\nQ4: Largest number:")
for n in numbers_tuple:
    if n > largest:
        largest = n
print("Largest number =", largest)

# Q5. Print student names with index number
students = ("Asha", "Rahul", "Meera", "Kiran", "Nisha")
print("\nQ5: Student names with index:")
for index, name in enumerate(students):
    print(index, name)

# Q6. Subjects and marks dictionary
subjects = {
    "Math": 90,
    "Science": 85,
    "English": 88,
    "Computer": 95,
    "History": 80
}
print("\nQ6: Subjects and marks:")
total_marks = 0
for subject, mark in subjects.items():
    print(subject, ":", mark)
    total_marks += mark
percentage = (total_marks / (len(subjects) * 100)) * 100
print("Total marks =", total_marks)
print("Percentage =", percentage, "%")


